def main():
    total = 0
    for f in FILES:
        if not os.path.exists(f):
            continue
        t = open(f, encoding="utf-8").read()
        orig = t
        # protect
        for suf, lit, ph in PROTECT:
            if f.endswith(suf) and lit in t:
                t = t.replace(lit, ph)
        for zh, vi in sorted(D.items(), key=lambda kv: -len(kv[0])):
            if zh and zh in t:
                t = t.replace(zh, vi)
        for suf, lit, ph in PROTECT:
            if f.endswith(suf) and ph in t:
                t = t.replace(ph, lit)
        if t != orig:
            open(f, "w", encoding="utf-8").write(t)
            print("translated", f.split("sett-stage-hospitalization/")[-1])
            total += 1
    print("files changed:", total)

if __name__ == "__main__":
    main()
