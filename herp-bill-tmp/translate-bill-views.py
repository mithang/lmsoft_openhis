def main():
    files = sorted(glob.glob("/home/hatch/workspace/openhis-core/herp-bill-tmp/Newtouch.Herp.Web/Areas/BillManage/Views/*/*.cshtml"))
    keys = sorted(M, key=len, reverse=True)
    total = 0
    for f in files:
        lines = open(f, encoding="utf-8-sig").read().split("\n")
        changed = 0
        for i, ln in enumerate(lines):
            if ln.strip().startswith("//") or ln.strip().startswith("<!--"):
                continue
            new = ln
            for k in keys:
                if k in new:
                    new = new.replace(k, M[k])
            if new != ln:
                lines[i] = new
                changed += 1
        if changed:
            open(f, "w", encoding="utf-8").write("\n".join(lines))
            print(f"{f.split('Views/')[1]}: {changed} lines")
            total += changed
    print("TOTAL changed lines:", total)

if __name__ == "__main__":
    main()
