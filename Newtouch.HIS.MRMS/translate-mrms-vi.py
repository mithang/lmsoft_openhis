ZH = re.compile(r"[\u4e00-\u9fff]+")


def main():
    keys = sorted(D.keys(), key=len, reverse=True)
    total_files = 0
    total_repl = 0
    per_file = {}
    for p in list(ROOT.rglob("*.cshtml")) + list(ROOT.rglob("*.cs")):
        if "obj" in p.parts or "bin" in p.parts:
            continue
        txt = p.read_text(encoding="utf-8", errors="ignore")
        orig = txt
        n = 0
        for k in keys:
            if k in txt:
                c = txt.count(k)
                txt = txt.replace(k, D[k])
                n += c
        if txt != orig:
            p.write_text(txt, encoding="utf-8")
            total_files += 1
            total_repl += n
            per_file[str(p.relative_to(ROOT))] = n
    print(f"files changed: {total_files}, replacements: {total_repl}")
    # remaining Chinese inventory
    rem = {}
    for p in list(ROOT.rglob("*.cshtml")) + list(ROOT.rglob("*.cs")):
        if "obj" in p.parts or "bin" in p.parts:
            continue
        txt = p.read_text(encoding="utf-8", errors="ignore")
        for m in ZH.finditer(txt):
            rem.setdefault(m.group(0), []).append(str(p.relative_to(ROOT)))
    print(f"remaining unique Chinese strings: {len(rem)}")
    for s, files in sorted(rem.items(), key=lambda kv: -len(kv[1]))[:120]:
        print(f"REMAIN {s} [{len(files)}x] {files[0]}")


